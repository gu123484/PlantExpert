def section_diagnosis():
    n0 = len(new_items)
    for bid, name, syms, keys in SYMPTOMS:
        b = blocks[bid]
        facts = dict(b["facts"])
        use = [(k, facts[k]) for k in keys if k in facts]
        if not use:
            print(f"[警告] {bid} 键不存在: {keys}")
            continue
        crop = b["crop"]
        for sym in syms:
            for w in rng.sample(WRAPS, 2):          # 每症状 2 种问法
                lead = rng.choice(["从描述看，很可能是", "您说的这些表现比较典型，多半是",
                                   "综合看更像", "这个症状符合"])
                ans = f"{lead}{name}。判别要点：{use[0][1]}。"
                ans += "；".join(f"{k}：{v}" for k, v in use[1:]) + "。"
                c = rng.choice(DIAG_CLOSERS)
                if c:
                    ans += c
                add(w(crop, sym), ans, "diagnosis", md(b, "diagnosis", "+".join(keys)))
    return len(new_items) - n0

