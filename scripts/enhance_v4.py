def section_triage():
    n0 = len(new_items)
    for q, crop, bids, a in TRIAGE:
        bl = [blocks[i] for i in bids]
        meta = {"作物": crop, "环节": bl[0]["stage"], "主题": "症状排查与鉴别",
                "地区": "", "生育期": "", "条件": "", "问题类型": "triage",
                "知识块": "+".join(b["id"] for b in bl), "事实键": "多块综合",
                "依据": "；".join(dict.fromkeys(b["source"] for b in bl))}
        add(q, a, "triage", meta)
